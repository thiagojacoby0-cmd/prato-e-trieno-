export function pickExercise(id: string, overrides?: Partial<WorkoutExercise>): WorkoutExercise {
  const base = EXERCISE_LIBRARY[id] || EXERCISE_LIBRARY['main-squat'];
  return {
    ...base,
    ...overrides,
  };
}

export function buildExercisesFromIds(ids: string[], stage?: WorkoutExercise['stage']): WorkoutExercise[] {
  return ids.map((id) => pickExercise(id, stage ? { stage } : undefined));
}

export function findSubstitutesForExercise(exercise: WorkoutExercise): WorkoutExercise[] {
  const all = Object.values(EXERCISE_LIBRARY).filter((e) => e.stage === (exercise.stage || 'main') && e.id !== exercise.id);
  const targets = new Set(exercise.target_muscles || []);
  const sameTarget = all.filter((e) => (e.target_muscles || []).some((m) => targets.has(m)));
  return (sameTarget.length >= 2 ? sameTarget : all).slice(0, 6);
}

export function inferArchetypeFromName(name: string): TutorialArchetype {
  const n = name.toLowerCase();
  if (n.includes('polichinelo') || n.includes('jumping jack')) return 'jumping_jack';
  if (n.includes('marcha') || n.includes('joelho alto') || n.includes('corrida')) return 'high_knees';
  if (n.includes('renegade') || (n.includes('flexão') && n.includes('remada'))) return 'renegade_row';
  if (n.includes('diamante')) return 'diamond_pushup';
  if (n.includes('inclinada')) return 'incline_pushup';
  if (n.includes('flexão') || n.includes('flexao')) return 'pushup';
  if (n.includes('escalador') || n.includes('mountain')) return 'mountain_climber';
  if (n.includes('burpee')) return 'burpee';
  if (n.includes('búlgaro') || n.includes('bulgaro')) return 'bulgarian';
  if (n.includes('sumô') || n.includes('sumo')) return 'sumo_squat';
  if (n.includes('salto')) return 'jump_squat';
  if (n.includes('agachamento') || n.includes('squat')) return 'squat';
  if (n.includes('afundo') || n.includes('avanço')) return 'lunge';
  if (n.includes('panturrilha')) return 'calf_raise';
  if (n.includes('mergulho') || n.includes('tríceps') || n.includes('triceps')) return 'tricep_dip';
  if (n.includes('rosca') || n.includes('bíceps') || n.includes('biceps')) return 'bicep_curl';
  if (n.includes('elevação lateral') || n.includes('elevacao lateral')) return 'lateral_raise';
  if (n.includes('desenvolvimento') || n.includes('ombro')) return 'shoulder_press';
  if (n.includes('remada')) return 'bent_row';
  if (n.includes('superman')) return 'superman';
  if (n.includes('elevação pélvica') || n.includes('elevacao pelvica') || n.includes('ponte')) return 'glute_bridge';
  if (n.includes('coice')) return 'donkey_kick';
  if (n.includes('hidrante') || n.includes('abdução')) return 'fire_hydrant';
  if (n.includes('dead bug') || n.includes('inseto')) return 'dead_bug';
  if (n.includes('prancha lateral')) return 'side_plank';
  if (n.includes('prancha')) return 'plank';
  if (n.includes('bicicleta')) return 'bicycle_crunch';
  if (n.includes('torção russa') || n.includes('russian')) return 'russian_twist';
  if (n.includes('elevação de pernas') || n.includes('infra')) return 'leg_raise';
  if (n.includes('abdominal') || n.includes('supra')) return 'crunch';
  if (n.includes('círculos') || n.includes('ombros e braços')) return 'arm_circles';
  if (n.includes('rotação dinâmica') || n.includes('tronco')) return 'torso_twist';
  if (n.includes('gato') || n.includes('camelo')) return 'cat_camel';
  if (n.includes('criança') || n.includes('postura')) return 'child_pose';
  if (n.includes('cobra')) return 'cobra_stretch';
  if (n.includes('posteriores')) return 'hamstring_stretch';
  if (n.includes('maior alongamento') || n.includes('mobilidade')) return 'mobility_twist';
  return 'squat';
}
